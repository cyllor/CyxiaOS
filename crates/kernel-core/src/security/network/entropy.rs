//! V0.20 native entropy health gates and epoch-bound HMAC_DRBG/SHA-256.
use super::{Error, hmac_sha256, hmac_sha256_parts};
use zeroize::{Zeroize, Zeroizing};

const PERSONALIZATION: &[u8] = b"CYX/DRBG/v1";
const TLS_LABEL: &[u8] = b"CYX/TLS/v1";
const TCP_ISN_LABEL: &[u8] = b"CYX/TCP-ISN/v1";
const ASLR_LABEL: &[u8] = b"CYX/ASLR/v1";
pub const INIT_SEED_BYTES: usize = 48;
pub const RESEED_BYTES: usize = 32;
pub const MAX_REQUEST_BYTES: usize = 4096;
const RESEED_CALLS: u32 = 65_536;
const RESEED_MS: u64 = 600_000;

// Best-effort online checks on the trusted VirtIO samples. These thresholds
// detect gross source failures and do not estimate a physical min-entropy rate.
pub const HEALTH_STARTUP_SAMPLES: usize = 1024;
const REPETITION_CUTOFF: u8 = 8;
const PROPORTION_WINDOW: u16 = 512;
const PROPORTION_CUTOFF: u16 = 32;

#[derive(Default)]
pub struct RawHealth {
    previous: u8,
    repeat: u8,
    reference: u8,
    matches: u16,
    window_samples: u16,
    failed: bool,
}

impl RawHealth {
    /// Keep repetition and adaptive-proportion state across source reads.
    /// A failure latches until the source is reinitialized by a new boot.
    pub fn observe(&mut self, samples: &[u8]) -> Result<(), Error> {
        if self.failed {
            return Err(Error::Unauthorized);
        }
        for &sample in samples {
            if self.repeat == 0 || sample != self.previous {
                self.previous = sample;
                self.repeat = 1;
            } else {
                self.repeat += 1;
            }
            if self.window_samples == 0 {
                self.reference = sample;
                self.matches = 0;
            }
            self.window_samples += 1;
            self.matches += u16::from(sample == self.reference);
            if self.repeat >= REPETITION_CUTOFF || self.matches >= PROPORTION_CUTOFF {
                self.failed = true;
                return Err(Error::Unauthorized);
            }
            if self.window_samples == PROPORTION_WINDOW {
                self.window_samples = 0;
            }
        }
        Ok(())
    }
}

impl Drop for RawHealth {
    fn drop(&mut self) {
        self.previous.zeroize();
        self.reference.zeroize();
    }
}

// SP 800-90A Rev. 1 §10.1.2. Generate and reseed have no caller-controlled
// additional input. Quotas, time and mandatory reseeding live in NetworkRandom.
struct HmacDrbg {
    key: [u8; 32],
    value: [u8; 32],
}

impl HmacDrbg {
    fn from_material(material: &[u8]) -> Self {
        let mut out = Self {
            key: [0; 32],
            value: [1; 32],
        };
        out.update(material);
        out
    }

    fn instantiate(seed: &[u8; INIT_SEED_BYTES]) -> Self {
        let mut material = Zeroizing::new([0u8; INIT_SEED_BYTES + PERSONALIZATION.len()]);
        material[..INIT_SEED_BYTES].copy_from_slice(seed);
        material[INIT_SEED_BYTES..].copy_from_slice(PERSONALIZATION);
        Self::from_material(&material[..])
    }

    fn update_round(&mut self, separator: u8, provided: &[u8]) {
        let next = Zeroizing::new(hmac_sha256_parts(
            &self.key,
            &[&self.value, &[separator], provided],
        ));
        self.key.zeroize();
        self.key.copy_from_slice(&next[..]);
        self.advance();
    }

    fn update(&mut self, provided: &[u8]) {
        self.update_round(0, provided);
        if !provided.is_empty() {
            self.update_round(1, provided);
        }
    }

    fn advance(&mut self) {
        let next = Zeroizing::new(hmac_sha256(&self.key, &self.value));
        self.value.zeroize();
        self.value.copy_from_slice(&next[..]);
    }

    fn generate(&mut self, output: &mut [u8]) {
        for chunk in output.chunks_mut(32) {
            self.advance();
            chunk.copy_from_slice(&self.value[..chunk.len()]);
        }
        self.update(&[]);
    }

    fn zeroize(&mut self) {
        self.key.zeroize();
        self.value.zeroize();
    }
}

impl Drop for HmacDrbg {
    fn drop(&mut self) {
        self.zeroize();
    }
}

#[derive(Clone, Copy)]
pub enum Domain {
    Tls,
    TcpIsn,
    Aslr,
}

/// The root instance generates a fresh 32-byte master at each key epoch.
/// Independent HKDF keys initialize dedicated stream states. Only bytes
/// generated by those streams leave this owner.
pub struct NetworkRandom {
    root: HmacDrbg,
    tls: HmacDrbg,
    tcp_isn: HmacDrbg,
    aslr: HmacDrbg,
    boot_epoch: u64,
    key_epoch: u64,
    seeded_at_ms: u64,
    observed_ms: u64,
    calls: u32,
    closed: bool,
}

impl NetworkRandom {
    /// Caller supplies the 32-byte entropy input plus 16-byte nonce from a
    /// trusted source after the source health gate has completed.
    pub fn new(seed: &[u8; INIT_SEED_BYTES], boot_epoch: u64, now_ms: u64) -> Result<Self, Error> {
        if boot_epoch == 0 {
            return Err(Error::Invalid);
        }
        let mut root = HmacDrbg::instantiate(seed);
        let (tls, tcp_isn, aslr) = Self::derive_domains(&mut root, boot_epoch, 1);
        Ok(Self {
            root,
            tls,
            tcp_isn,
            aslr,
            boot_epoch,
            key_epoch: 1,
            seeded_at_ms: now_ms,
            observed_ms: now_ms,
            calls: 0,
            closed: false,
        })
    }

    fn derive_domains(
        root: &mut HmacDrbg,
        boot_epoch: u64,
        key_epoch: u64,
    ) -> (HmacDrbg, HmacDrbg, HmacDrbg) {
        let mut master = Zeroizing::new([0u8; 32]);
        root.generate(&mut master[..]);
        let prk = Zeroizing::new(hmac_sha256(&[0; 32], &master[..]));
        master.zeroize();
        let boot = boot_epoch.to_le_bytes();
        let key = key_epoch.to_le_bytes();
        let instantiate = |label: &[u8]| {
            let domain = Zeroizing::new(hmac_sha256_parts(
                &prk[..],
                &[label, &[0], &boot, &key, &[1]],
            ));
            let mut seed = Zeroizing::new([0u8; INIT_SEED_BYTES]);
            seed[..32].copy_from_slice(&domain[..]);
            seed[32..40].copy_from_slice(&boot);
            seed[40..].copy_from_slice(&key);
            HmacDrbg::instantiate(&seed)
        };
        (
            instantiate(TLS_LABEL),
            instantiate(TCP_ISN_LABEL),
            instantiate(ASLR_LABEL),
        )
    }

    fn observe_clock(&mut self, now_ms: u64) -> Result<(), Error> {
        if self.closed {
            return Err(Error::Unauthorized);
        }
        if now_ms < self.observed_ms {
            self.close();
            return Err(Error::Stale);
        }
        self.observed_ms = now_ms;
        Ok(())
    }

    pub fn reseed_due(&mut self, now_ms: u64) -> Result<bool, Error> {
        self.observe_clock(now_ms)?;
        Ok(self.calls >= RESEED_CALLS || now_ms - self.seeded_at_ms >= RESEED_MS)
    }

    /// Replace the old domain streams only after accepting fresh entropy.
    pub fn reseed(&mut self, entropy: &[u8; RESEED_BYTES], now_ms: u64) -> Result<(), Error> {
        self.observe_clock(now_ms)?;
        let Some(next_epoch) = self.key_epoch.checked_add(1) else {
            self.close();
            return Err(Error::Exhausted);
        };
        self.root.update(entropy);
        (self.tls, self.tcp_isn, self.aslr) =
            Self::derive_domains(&mut self.root, self.boot_epoch, next_epoch);
        self.key_epoch = next_epoch;
        self.seeded_at_ms = now_ms;
        self.calls = 0;
        Ok(())
    }

    pub const fn key_epoch(&self) -> u64 {
        self.key_epoch
    }

    /// Do not generate until fresh reseeding has completed when required.
    pub fn fill(&mut self, domain: Domain, output: &mut [u8], now_ms: u64) -> Result<(), Error> {
        let permitted = self.reseed_due(now_ms).and_then(|due| {
            if due {
                Err(Error::Busy)
            } else if output.len() > MAX_REQUEST_BYTES {
                Err(Error::Invalid)
            } else {
                Ok(())
            }
        });
        if let Err(error) = permitted {
            output.zeroize();
            return Err(error);
        }
        if !output.is_empty() {
            let stream = match domain {
                Domain::Tls => &mut self.tls,
                Domain::TcpIsn => &mut self.tcp_isn,
                Domain::Aslr => &mut self.aslr,
            };
            stream.generate(output);
            self.calls += 1;
        }
        Ok(())
    }

    /// Fail closed on a source, clock or generation failure. No old generation
    /// can be served again even if the source resumes reporting samples.
    pub fn close(&mut self) {
        self.root.zeroize();
        self.tls.zeroize();
        self.tcp_isn.zeroize();
        self.aslr.zeroize();
        self.closed = true;
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn sequence<const N: usize>(start: u8) -> [u8; N] {
        core::array::from_fn(|index| start.wrapping_add(index as u8))
    }

    fn unhex<const N: usize>(s: &str) -> [u8; N] {
        assert_eq!(s.len(), 2 * N);
        core::array::from_fn(|i| u8::from_str_radix(&s[i * 2..i * 2 + 2], 16).unwrap())
    }

    #[test]
    fn matches_nist_sha256_example() {
        // NIST HMAC_DRBG.pdf, first SHA-256 example, first two Generate
        // calls (no personalization, additional input or prediction resistance).
        let mut material = [0; 63];
        material[..55].copy_from_slice(&sequence::<55>(0));
        material[55..].copy_from_slice(&sequence::<8>(0x20));
        let mut drbg = HmacDrbg::from_material(&material);
        let mut output = [0; 64];
        drbg.generate(&mut output);
        assert_eq!(
            output,
            unhex(concat!(
                "d67b8c1734f46fa3f763cf57c6f9f4f2dc1089bd8bc1f6f023950bfc56176352",
                "08c8501238ad7a4400defee46c640b61af77c2d1a3bfaa90ede5d207406e5403",
            ))
        );
        drbg.generate(&mut output);
        assert_eq!(
            output,
            unhex(concat!(
                "8fdaec20f8b421407059e3588920da7eda9dce3cf8274dfa1c59c108c1d0aa9b",
                "0fa38da5c792037c4d33cd070ca7cd0c5608dba8b885654639de2187b74cb263",
            ))
        );
    }

    #[test]
    fn health_checks_preserve_repetition_and_proportion_across_chunks() {
        let good = sequence::<HEALTH_STARTUP_SAMPLES>(1);
        let mut repeat = RawHealth::default();
        for chunk in good.chunks(121) {
            repeat.observe(chunk).unwrap();
        }
        assert_eq!(repeat.observe(&[9; 7]), Ok(()));
        assert_eq!(repeat.observe(&[9]), Err(Error::Unauthorized));
        assert_eq!(repeat.observe(&good), Err(Error::Unauthorized));

        let mut proportion = RawHealth::default();
        for _ in 0..31 {
            assert_eq!(proportion.observe(&[3, 4]), Ok(()));
        }
        assert_eq!(proportion.observe(&[3]), Err(Error::Unauthorized));
    }

    #[test]
    fn domains_are_independent_and_boot_epoch_bound() {
        let seed = sequence::<INIT_SEED_BYTES>(1);
        let mut a = NetworkRandom::new(&seed, 1, 10).unwrap();
        let mut b = NetworkRandom::new(&seed, 1, 10).unwrap();
        let mut newer = NetworkRandom::new(&seed, 2, 10).unwrap();
        let (mut tcp, mut tls, mut same, mut other) = ([0; 32], [0; 32], [0; 32], [0; 32]);
        a.fill(Domain::TcpIsn, &mut tcp, 10).unwrap();
        a.fill(Domain::Tls, &mut tls, 10).unwrap();
        b.fill(Domain::Tls, &mut same, 10).unwrap();
        newer.fill(Domain::Tls, &mut other, 10).unwrap();
        assert_eq!(tls, same);
        assert_ne!(tls, tcp);
        assert_ne!(tls, other);
        a.fill(Domain::Tls, &mut same, 10).unwrap();
        assert_ne!(tls, same);

        let mut aslr = [0; 32];
        a.fill(Domain::Aslr, &mut aslr, 10).unwrap();
        b.fill(Domain::Aslr, &mut same, 10).unwrap();
        newer.fill(Domain::Aslr, &mut other, 10).unwrap();
        assert_eq!(aslr, same);
        assert_ne!(aslr, tls);
        assert_ne!(aslr, tcp);
        assert_ne!(aslr, other);
    }

    #[test]
    fn exact_reseed_boundaries_zero_stale_outputs_and_rotate_epoch() {
        let seed = sequence::<INIT_SEED_BYTES>(0);
        let mut state = NetworkRandom::new(&seed, 42, 123).unwrap();
        let mut ordinary = [0; 32];
        state.fill(Domain::Tls, &mut ordinary, 123).unwrap();
        state.calls = RESEED_CALLS - 1;
        let mut output = [0xff; 32];
        state.fill(Domain::TcpIsn, &mut output, 123).unwrap();
        assert_eq!(state.fill(Domain::Tls, &mut output, 123), Err(Error::Busy));
        assert_eq!(output, [0; 32]);
        state.reseed(&sequence::<RESEED_BYTES>(80), 123).unwrap();
        assert_eq!(state.key_epoch(), 2);
        state
            .fill(Domain::Tls, &mut output, 123 + RESEED_MS - 1)
            .unwrap();
        assert_ne!(output, ordinary);
        assert_eq!(
            state.fill(Domain::Tls, &mut output, 123 + RESEED_MS),
            Err(Error::Busy)
        );
        assert_eq!(output, [0; 32]);
    }

    #[test]
    fn length_clock_and_epoch_failures_cannot_publish_bytes() {
        let mut state = NetworkRandom::new(&sequence::<INIT_SEED_BYTES>(0), 1, 10).unwrap();
        let mut output = [0xff; MAX_REQUEST_BYTES + 1];
        assert_eq!(
            state.fill(Domain::Tls, &mut output, 10),
            Err(Error::Invalid)
        );
        assert_eq!(output, [0; MAX_REQUEST_BYTES + 1]);
        state
            .fill(Domain::Tls, &mut output[..MAX_REQUEST_BYTES], 10)
            .unwrap();
        assert_eq!(
            state.fill(Domain::Tls, &mut output[..8], 9),
            Err(Error::Stale)
        );
        assert_eq!(&output[..8], &[0; 8]);
        assert_eq!(
            state.reseed(&[1; RESEED_BYTES], 11),
            Err(Error::Unauthorized)
        );
        assert!(state.closed && state.root.key == [0; 32] && state.tls.key == [0; 32]);

        let mut last = NetworkRandom::new(&sequence::<INIT_SEED_BYTES>(0), 1, 1).unwrap();
        last.key_epoch = u64::MAX;
        assert_eq!(last.reseed(&[1; RESEED_BYTES], 1), Err(Error::Exhausted));
        assert_eq!(
            last.fill(Domain::TcpIsn, &mut output[..8], 1),
            Err(Error::Unauthorized)
        );
        assert_eq!(&output[..8], &[0; 8]);
    }
}
