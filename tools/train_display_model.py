"""Reproduce the bounded display pacing model; synthetic policy distillation.

The model chooses whether to spend one millisecond of a strict pacing budget.
Its feedback is the previous completed GPU fence latency, never pixel/input data.
This is not online learning or evidence of better desktop performance.
"""
import argparse
import json
import random
from pathlib import Path

from train_fs_model import fit, score

ROOT = Path(__file__).resolve().parents[1]
SEED = 0x43595844


def features(latency, completed_since_wait):
    return [1, min(latency, 16), min(completed_since_wait, 8), 0]


def generate():
    data = [(features(latency, burst), latency >= 4 and burst == 8)
            for latency in range(17) for burst in range(9)]
    random.Random(SEED).shuffle(data)
    weights = fit(data, epochs=256)
    rng = random.Random(SEED + 1)
    validation = [(rng.randrange(251), rng.randrange(65)) for _ in range(4096)]
    correct = sum((score(weights, features(latency, burst)) >= 0)
                  == (latency >= 4 and burst >= 8) for latency, burst in validation)
    report = dict(model=0x6001, version=1, seed=SEED, epochs=256,
                  weights=weights, exhaustive_feature_training_samples=len(data),
                  training_correct=sum((score(weights, x) >= 0) == y for x, y in data),
                  validation_raw_observations=len(validation), validation_correct=correct,
                  max_delay_ms=1, min_completed_between_waits=8,
                  limitation="Synthetic teacher conformance. Validation uses unseen raw observations "
                             "mapped to trained bounded features; not held-out workload performance "
                             "or online learning. Actual foreground scheduling can add queue latency.")
    source = "// Generated by tools/train_display_model.py; synthetic teacher distillation.\n"
    source += f"pub const DISPLAY: [i32; 4] = {weights};\n"
    return source, json.dumps(report, indent=2) + "\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, value in zip((ROOT / "crates/ai-runtime/src/display_weights.rs",
                            ROOT / "docs/implementation/display-model-training.json"), generate()):
        if args.check:
            if path.read_text() != value:
                raise SystemExit(f"Display model artifact mismatch: {path}")
        else:
            path.write_text(value)
    print("Display model reproducible" if args.check else generate()[1])
