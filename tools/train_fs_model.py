"""Reproducible integer perceptrons; synthetic data, no file contents.
Run --check to verify the checked-in parameters without modifying them.
"""
import argparse
import json
from pathlib import Path
import random

ROOT = Path(__file__).resolve().parents[1]


def score(weights, x):
    return sum(a * b for a, b in zip(weights, x))


def fit(samples, epochs=8):
    weights = [0] * len(samples[0][0])
    for _ in range(epochs):
        for x, label in samples:
            if (score(weights, x) >= 0) != label:
                sign = 1 if label else -1
                weights = [max(-512, min(512, w + sign * v)) for w, v in zip(weights, x)]
    return weights


def generate():
    rng = random.Random(0x435958)
    admission = []
    for _ in range(2048):
        free = rng.randrange(33)
        growth = rng.randrange(5)
        x = [1, free, growth, 0]
        admission.append((x, free * 4 >= growth))
    # Two hot files interspersed with a cold scan. Labels refer to future accesses.
    trace = [rng.randrange(2) if rng.randrange(4) else rng.randrange(2, 16) for _ in range(1200)]
    hits, last, reuse = [0] * 16, [0] * 16, []
    for t, file in enumerate(trace[:-1], 1):
        hits[file] = min(hits[file] + 1, 16)
        last[file] = t
        for candidate in range(16):
            x = [1, hits[candidate], min(t - last[candidate], 16), 1 + candidate % 4]
            reuse.append((x, candidate in trace[t:t + 1]))
    raw_train, validation = reuse[:12000], reuse[12000:]
    positives = [s for s in raw_train if s[1]]
    negatives = [s for s in raw_train if not s[1]]
    rng.shuffle(negatives)
    train = positives + negatives[:len(positives)]
    rng.shuffle(train)
    # Extend only admission to the desktop RAMFS domain; preserve the original
    # cache-ranking dataset and RNG stream. Every free/growth pair is covered.
    admission = [([1, free, growth, 0], free * 4 >= growth)
                 for free in range(65) for growth in range(17)]
    random.Random(0x43595841).shuffle(admission)
    aw, rw = fit(admission, epochs=32), fit(train)
    canary = [s for s in validation if s[1]][:8] + [s for s in validation if not s[1]][:8]
    lines = ['// Generated by tools/train_fs_model.py; synthetic training, integer inference.',
             f'pub const ADMISSION: [i32; 4] = {aw};', f'pub const REUSE: [i32; 4] = {rw};',
             'pub const CANARY: [([i32; 4], bool); 16] = [']
    lines += [f'    ({x}, {str(y).lower()}),' for x, y in canary]
    lines += ['];', '']
    report = dict(seed=0x435958, epochs=8, admission_samples=len(admission), admission_domain=dict(free=[0,64], growth_256byte_units=[0,16]), admission_epochs=32, reuse_samples=len(train),
                  heldout_samples=len(validation), admission_weights=aw, reuse_weights=rw,
                  heldout_correct=sum((score(rw, x) >= 0) == y for x, y in validation),
                  limitation='Synthetic workload only; no production performance claim.')
    return '\n'.join(lines), json.dumps(report, indent=2) + '\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    source, report = generate()
    for path, value in [(ROOT / 'crates/ai-fs/src/weights.rs', source),
                        (ROOT / 'docs/implementation/fs-model-training.json', report)]:
        if args.check:
            if path.read_text() != value:
                raise SystemExit(f'Model artifact mismatch: {path}')
        else:
            path.write_text(value)
    print(report)
