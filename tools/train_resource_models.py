"""Integer perceptron policy distillation from explicit synthetic teacher objectives.
No production-performance claims. Policy choice is separate from hard kernel constraints.
"""
import argparse
import json
import random
from pathlib import Path
from train_fs_model import fit, score
ROOT = Path(__file__).resolve().parents[1]


def generate():
    rng = random.Random(0x43595852)
    datasets = {}
    # Memory: leave approximately two free pages for subsequent requests.
    datasets['MEMORY'] = [([1, free, need, 0], free - need >= 2)
                          for free in range(33) for need in range(1, 9)]
    # Pairwise preference: age and priority dominate remaining work under this teacher.
    pairs = []
    for _ in range(3000):
        x = [0, rng.randrange(-32, 33), rng.randrange(-3, 4), rng.randrange(-16, 17)]
        pairs.append((x, 4*x[1] + 8*x[2] - x[3] >= 0))
    datasets['CPU'] = pairs
    datasets['QUANTUM'] = [([1, ready, remaining, 0], ready <= 2 and remaining >= 4)
                            for ready in range(1, 9) for remaining in range(1, 17)]
    pairs = []
    for _ in range(3000):
        x = [0, rng.randrange(-32, 33), rng.randrange(-3, 4), rng.randrange(-4, 5)]
        pairs.append((x, 8*x[1] + 4*x[2] - 2*x[3] >= 0))
    datasets['DEVICE'] = pairs
    # User dispatch: CPU-bound code may get 4 ms only without competing EL1 tasks.
    datasets['USER_QUANTUM'] = [([1, cpu_bound, busy, 0], cpu_bound == 1 and busy == 0)
                               for cpu_bound in range(2) for busy in range(9)]
    # Anonymous memory: units of 16 pages; keep approximately 32 pages available.
    datasets['USER_MEMORY'] = [([1, free, need, 0], free - need >= 2)
                               for free in range(257) for need in range(1, 129)]
    datasets['EXEC_MEMORY'] = [([1, free, need, 0], free - need >= 2)
                               for free in range(257) for need in range(1, 257)]
    lines = ['// Generated by tools/train_resource_models.py; synthetic teacher distillation.']
    report = {'seed': 0x43595852, 'models': {}, 'limitation': 'Synthetic policy distillation; not workload performance validation.'}
    for name, data in datasets.items():
        rng.shuffle(data)
        cut = len(data)*4//5
        train, heldout = data[:cut], data[cut:]
        w = fit(train, epochs=32)
        lines.append(f'pub const {name}: [i32; 4] = {w};')
        report['models'][name] = dict(version=1, weights=w, train=len(train), heldout=len(heldout),
                                     correct=sum((score(w,x)>=0)==y for x,y in heldout))
    return '\n'.join(lines)+'\n', json.dumps(report,indent=2)+'\n'


if __name__ == '__main__':
    p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args()
    for path, text in zip([ROOT/'crates/ai-runtime/src/weights.rs', ROOT/'docs/implementation/resource-model-training.json'], generate()):
        if args.check:
            if path.read_text()!=text:raise SystemExit(f'Parameters differ: {path}')
        else:path.write_text(text)
    print('Resource models reproducible' if args.check else generate()[1])
