"""Reproducible bounded checkpoint-share model; synthetic policy distillation.

This freezes a declared target, not evidence of a performance improvement:
with at most one runnable work item permit four operations per 8 ms window;
with competing work permit one. Work counts user processes plus eligible EL1
tasks, clipped to eight. Completion is never subject to this
new-submission budget. --check never changes files.
"""
import argparse
import json
from pathlib import Path
import random

ROOT = Path(__file__).resolve().parents[1]


def generate():
    samples = [([1, runnable], runnable <= 1) for runnable in range(9)]
    random.Random(0x43595853).shuffle(samples)
    weights = [0, 0]
    for _ in range(32):
        for features, high_share in samples:
            prediction = sum(w * x for w, x in zip(weights, features)) >= 0
            if prediction != high_share:
                sign = 1 if high_share else -1
                weights = [w + sign * x for w, x in zip(weights, features)]
    correct = sum((sum(w*x for w, x in zip(weights, features)) >= 0) == label
                  for features, label in samples)
    if correct != len(samples):
        raise AssertionError('Incomplete bounded-domain fit')
    source = ('// Generated by tools/train_storage_model.py; synthetic policy distillation.\n'
              f'pub const SHARE: [i32; 2] = {weights};\n')
    report = dict(model_id=20481, schema_version=1, seed=0x43595853,
                  epochs=32, features=['bias', 'runnable_work'],
                  domain=dict(runnable_work=[0, 8]), samples=9,
                  domain_correct=correct, weights=weights,
                  operations_per_window=[1, 4], window_ms=8,
                  limitation='Exhaustive fit to a synthetic target; no held-out workload or performance benefit claim; no online learning.')
    return source, json.dumps(report, indent=2) + '\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    source, report = generate()
    for path, expected in [(ROOT/'crates/ai-runtime/src/storage_weights.rs', source),
                           (ROOT/'docs/implementation/storage-model-training.json', report)]:
        if args.check:
            if path.read_text() != expected:
                raise SystemExit(f'Model artifact mismatch: {path}')
        else:
            path.write_text(expected)
    print(report)
