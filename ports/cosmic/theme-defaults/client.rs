//! Explicit one-shot exporter of the pinned upstream built-in theme defaults.
use cosmic_config::CosmicConfigEntry;
use cosmic_theme::{DARK_THEME_ID, LIGHT_THEME_ID, Theme};
use std::error::Error;
use std::fmt::Write as _;
use std::fs;
use std::io::{self, Write};
use std::path::{Path, PathBuf};

type Result<T> = std::result::Result<T, Box<dyn Error>>;
const SOURCE: &str = "libcosmic@5a8bd9482a35ae94c1e54edf77b331c6b970f170";
const KEY_COUNT: usize = 39;
const MAX_KEY_BYTES: usize = 8192;
const MAX_TOTAL_BYTES: usize = 256 * 1024;

fn directory(id: &str) -> Result<PathBuf> {
    if std::env::var_os("FLATPAK_ID").is_some() {
        return Err("generation requires an ordinary fresh guest config home".into());
    }
    let root = match std::env::var_os("XDG_CONFIG_HOME") {
        Some(value) if !value.is_empty() => PathBuf::from(value),
        _ => PathBuf::from(std::env::var_os("HOME").ok_or("HOME is unavailable")?).join(".config"),
    };
    if !root.is_absolute()
        || root
            .components()
            .any(|p| p == std::path::Component::ParentDir)
    {
        return Err("configuration home must be an absolute path without parent traversal".into());
    }
    let path = root.join("cosmic").join(id).join("v2");
    for ancestor in path.ancestors() {
        match fs::symlink_metadata(ancestor) {
            Ok(metadata) if metadata.is_dir() && !metadata.file_type().is_symlink() => {}
            Ok(_) => return Err("configuration path has a non-directory or symlink".into()),
            Err(error) if error.kind() == io::ErrorKind::NotFound => {}
            Err(error) => return Err(error.into()),
        }
    }
    Ok(path)
}

fn require_pristine(path: &Path) -> Result<()> {
    match fs::read_dir(path) {
        Ok(mut entries) => {
            if let Some(entry) = entries.next() {
                entry?;
                return Err(
                    "refusing to overwrite a nonempty theme configuration directory".into(),
                );
            }
        }
        Err(error) if error.kind() == io::ErrorKind::NotFound => {}
        Err(error) => return Err(error.into()),
    }
    Ok(())
}

fn snapshot(path: &Path) -> Result<Vec<(String, Vec<u8>)>> {
    let mut files = Vec::new();
    let mut total = 0usize;
    for entry in fs::read_dir(path)? {
        let entry = entry?;
        let name = entry
            .file_name()
            .into_string()
            .map_err(|_| "non-UTF-8 config key")?;
        if name.is_empty()
            || name.starts_with(".atomicwrite")
            || !name
                .bytes()
                .all(|byte| byte.is_ascii_lowercase() || byte == b'_')
            || !entry.file_type()?.is_file()
        {
            return Err("unexpected file or unclean atomic-write directory".into());
        }
        if entry.metadata()?.len() > MAX_KEY_BYTES as u64 {
            return Err("generated config key exceeds the guest file bound".into());
        }
        let data = fs::read(entry.path())?;
        total = total
            .checked_add(data.len())
            .ok_or("generated byte count overflow")?;
        if data.is_empty() || data.len() > MAX_KEY_BYTES || total > MAX_TOTAL_BYTES {
            return Err("generated configuration exceeds its byte bounds".into());
        }
        files.push((name, data));
        if files.len() > KEY_COUNT {
            return Err("unexpected extra config key".into());
        }
    }
    files.sort_unstable_by(|left, right| left.0.cmp(&right.0));
    if files.len() != KEY_COUNT || files.windows(2).any(|pair| pair[0].0 == pair[1].0) {
        return Err("pinned theme key count or uniqueness differs".into());
    }
    Ok(files)
}

fn run() -> Result<()> {
    let arguments: Vec<_> = std::env::args().collect();
    if arguments.len() != 2 || !matches!(arguments[1].as_str(), "light" | "dark") {
        return Err("usage: cosmic-theme-defaults {light|dark}".into());
    }
    if Theme::VERSION != 2 {
        return Err("pinned Theme schema is no longer version 2".into());
    }
    let mode = &arguments[1];
    let dark = mode == "dark";
    let id = if dark { DARK_THEME_ID } else { LIGHT_THEME_ID };
    let path = directory(id)?;
    require_pristine(&path)?;
    let theme = if dark {
        Theme::dark_default()
    } else {
        Theme::light_default()
    };
    if theme.is_dark != dark {
        return Err("upstream built-in theme has the wrong mode".into());
    }
    let config = if dark {
        Theme::dark_config()?
    } else {
        Theme::light_config()?
    };
    theme.write_entry(&config)?;
    let first = snapshot(&path)?;
    let recovered = Theme::get_entry(&config)
        .map_err(|(errors, _)| format!("upstream theme readback failed: {errors:?}"))?;
    if recovered.is_dark != dark || recovered.name != theme.name {
        return Err("upstream theme readback has a different identity".into());
    }
    // Upstream ColorRepr deliberately quantizes f32 colors into u8 hex.
    // Canonical key bytes, rather than pre-serialization float equality,
    // prove that the complete upstream write/read/write cycle is stable.
    recovered.write_entry(&config)?;
    if snapshot(&path)? != first {
        return Err("upstream theme serialization is not canonically stable".into());
    }
    // AtomicFile syncs before its temporary directory is dropped. Persist
    // that cleanup too, and emit nothing until the full readback has passed.
    fs::File::open(&path)?.sync_all()?;
    let mut output = io::stdout().lock();
    writeln!(
        output,
        "THEME_DEFAULTS BEGIN mode={mode} id={id} version=2 keys={KEY_COUNT} source={SOURCE}"
    )?;
    for (name, data) in first {
        let mut hex = String::with_capacity(data.len() * 2);
        for byte in &data {
            write!(hex, "{byte:02x}")?;
        }
        writeln!(
            output,
            "THEME_DEFAULTS KEY name={name} bytes={} hex={hex}",
            data.len()
        )?;
    }
    writeln!(output, "THEME_DEFAULTS PASS mode={mode} keys={KEY_COUNT}")?;
    output.flush()?;
    Ok(())
}

fn main() {
    if let Err(error) = run() {
        eprintln!("THEME_DEFAULTS FAIL: {error}");
        std::process::exit(1);
    }
}
